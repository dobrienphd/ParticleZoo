#!/usr/bin/env python3
"""Regenerate src/particlezoo/_pz.pyi, the type stub for the compiled module.

Run this after changing the bindings, with the updated package and
pybind11-stubgen installed in the active environment:

    pip install ./python pybind11-stubgen
    python python/scripts/generate_stubs.py

pybind11-stubgen does most of the work; the rest corrects the things it cannot
infer from the bindings' docstrings and drops noise from the result.
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

STUB = Path(__file__).resolve().parent.parent / "src" / "particlezoo" / "_pz.pyi"

HEADER = '''\
"""Type stub for the compiled ParticleZoo bindings.

Generated by python/scripts/generate_stubs.py - do not edit by hand.
"""
'''


def clean(text: str) -> str:
    # Replace the module docstring with a note on how the file is produced
    text = HEADER + re.sub(r'\A""".*?"""\n', "", text, flags=re.DOTALL)

    # These are only needed for re-exporting names; particlezoo/__init__.py has its own list
    text = re.sub(r"^__all__: .*\n", "", text, flags=re.MULTILINE)

    # pybind11 enums also copy their values into the module. The package does not
    # re-export them, and they would double the size of the stub
    text = re.sub(r"^\w+: (ParticleType|EGSLATCHOPTION)  # value = .*\n", "", text, flags=re.MULTILINE)

    # The value comments and the member lists in enum docstrings repeat the members themselves
    text = re.sub(r"  # value = .*$", "", text, flags=re.MULTILINE)
    text = re.sub(r"\n\s*\n    Members:\n.*?(?=\n    \"\"\")", "", text, flags=re.DOTALL)
    text = re.sub(r'    """\n    Members:\n.*?\n    """\n', "", text, flags=re.DOTALL)

    # pybind11 rejects floats for integer parameters, but float satisfies SupportsInt
    text = text.replace("typing.SupportsInt | typing.SupportsIndex", "typing.SupportsIndex")
    text = text.replace("typing.SupportsInt", "typing.SupportsIndex")

    # Fixed-size arrays are annotated as Annotated[list, FixedSize(n)]
    text = re.sub(r'typing\.Annotated\[(.*?), "FixedSize\(\d+\)"\]', r"\1", text)

    # CLICommand is not exposed to Python
    text = text.replace("cmd: ...", "cmd: typing.Any")

    # Enum comparisons accept any object; overloads for it are redundant
    for op in ("__eq__", "__ne__"):
        text = re.sub(
            rf"    @typing\.overload\n    def {op}\(self, other: \w+\) -> bool:\n        \.\.\.\n"
            rf"    @typing\.overload\n    def {op}\(self, other: typing\.Any\) -> bool:",
            f"    def {op}(self, other: object) -> bool:",
            text,
        )

    # FixedValues can only be compared with itself, and is therefore not hashable
    text = text.replace(
        "def __eq__(self, arg0: FixedValues) -> bool:",
        "def __eq__(self, arg0: FixedValues) -> bool:  # type: ignore[override]",
    )

    text = text.replace(
        "__hash__: typing.ClassVar[None] = None",
        "__hash__: typing.ClassVar[None] = None  # type: ignore[assignment]",
    )

    # Things the bindings do not describe
    text = text.replace("def all_particle_types() -> dict:", "def all_particle_types() -> dict[str, ParticleType]:")
    text = text.replace("def set_option(self, name: str, *args) -> None:",
                        "def set_option(self, name: str, *args: bool | int | float | str) -> None:")

    return re.sub(r"[ \t]+$", "", text, flags=re.MULTILINE)


def main() -> None:
    with tempfile.TemporaryDirectory() as out:
        subprocess.run(
            [sys.executable, "-m", "pybind11_stubgen", "particlezoo._pz", "-o", out, "--ignore-all-errors"],
            check=True,
        )
        text = (Path(out) / "particlezoo" / "_pz.pyi").read_text(encoding="utf-8")
    STUB.write_text(clean(text), encoding="utf-8")
    print(f"Wrote {STUB}")


if __name__ == "__main__":
    main()
